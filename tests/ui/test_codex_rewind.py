"""Keep native turn starts editable while refusing an exact later steer before any fork."""


class CodexRewind:
    def test_codex_resumed_identical_steer_is_labelled_and_refused_without_fork_or_send(self):
        terminal = self.launch(mode="codex-shared-turn", width=140)
        terminal.contains("you (steer)")
        terminal.contains("BEFORE_STEER_TOOL")
        terminal.contains("AFTER_STEER_REPORT")
        original = (terminal.root / "server-state.json").read_bytes()
        terminal.rewind("later prompt")
        terminal.send(b"\x1b[A")
        terminal.wait(lambda: terminal.input_is("same prompt 日本語"), "select exact steered item")
        terminal.replace_input("preserved edited steer 日本語")
        terminal.send(b"\r")
        terminal.contains("This message is a steer")
        self.assertTrue(terminal.input_is("preserved edited steer 日本語"))
        self.assertEqual(terminal.requests("thread/fork"), [])
        self.assertEqual(terminal.requests("turn/start"), [])
        self.assertEqual((terminal.root / "server-state.json").read_bytes(), original)
        self.assertGreaterEqual(len(terminal.requests("thread/items/list")), 2)
        terminal.contains("AFTER_STEER_REPORT")
        terminal.snapshot("steer-rejected-history-draft-kept")
        # Same visible text, but Up selects the first user item and is allowed.
        terminal.send(b"\x1b[A")
        terminal.wait(lambda: terminal.input_is("same prompt 日本語"), "select initial prompt with identical text")
        terminal.replace_input("initial prompt edited")
        terminal.send(b"\r")
        terminal.contains("Answer: initial prompt edited")
        self.assertEqual(terminal.requests("thread/fork")[0]["params"]["beforeTurnId"], "shared-turn")
        self.assertEqual(len(terminal.requests("turn/start")), 1)
        self.assertEqual(terminal.requests("turn/start")[0]["params"]["input"][0]["text"], "initial prompt edited")
        self.assertNotIn("BEFORE_STEER_TOOL", terminal.text)

    def test_codex_forked_prefix_keeps_steer_labels_and_exact_selection_after_reload(self):
        terminal = self.launch(mode="codex-shared-turn", width=54)
        terminal.contains("you (steer)")
        self.edit(terminal, "later prompt", "later edited")
        terminal.contains("you (steer)")
        terminal.contains("echo before steer")
        terminal.paste("/tools full")
        terminal.send(b"\r")
        terminal.contains("BEFORE_STEER_TOOL")
        terminal.rewind("later edited")
        terminal.send(b"\x1b[A")
        terminal.wait(lambda: terminal.input_is("same prompt 日本語"), "same exact steer after fork")
        terminal.replace_input("still cannot fork this steer")
        terminal.send(b"\r")
        terminal.contains("This message is a steer")
        self.assertEqual(len(terminal.requests("thread/fork")), 1)
        self.assertEqual(len(terminal.requests("turn/start")), 1)
        self.assertTrue(terminal.input_is("still cannot fork this steer"))
        terminal.snapshot("fork-prefix-steer-still-labelled")
