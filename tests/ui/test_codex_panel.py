"""Verify separate descendant details and exact selected stops through real terminal keys."""

class CodexPanel:
    def open_codex_panel(self,terminal):
        terminal.send(b"\x1bOQ")
        terminal.contains("Codex agents / processes")
        terminal.contains("Alpha 日本語")
        terminal.wait(lambda:"Reading agents" not in terminal.text,"complete native panel snapshot")

    def test_codex_f2_keeps_child_reports_tools_and_history_separate_while_stopping_exact_agent(self):
        terminal=self.launch(mode="codex-panel",width=120)
        terminal.contains("Answer: second")
        terminal.paste("preserved main draft 日本語")
        self.open_codex_panel(terminal)
        terminal.contains("EMBEDDED_CHILD_REPORT_HIDDEN")
        terminal.send(b"\r")
        terminal.contains("CHILD_DETAIL_ONLY 日本語")
        terminal.contains("CHILD_TOOL_ONLY")
        self.assertEqual(terminal.requests("thread/resume")[0]["params"]["threadId"],"thread-original")
        self.assertEqual(len(terminal.requests("thread/resume")),1)
        terminal.send(b"x")
        terminal.wait(lambda:bool(terminal.requests("turn/interrupt")),"selected child stop")
        self.assertEqual(terminal.requests("turn/interrupt")[0]["params"],{"threadId":"child-a","turnId":"child-turn"})
        terminal.send(b"\x1bOQ")
        terminal.wait(lambda:terminal.input_is("preserved main draft 日本語"),"main draft after child stop")
        terminal.contains("MAIN_TOOL_VISIBLE")
        for sentinel in ["CHILD_DETAIL_ONLY","CHILD_TOOL_ONLY","CHILD_TOOL_RESULT_ONLY","EMBEDDED_CHILD_REPORT_HIDDEN"]:
            self.assertNotIn(sentinel,terminal.text)
        self.assertEqual(terminal.requests("turn/start"),[])
        self.assertEqual(terminal.requests("turn/steer"),[])
        terminal.snapshot("child-detail-and-stop-with-main-draft")

    def test_codex_f2_phone_process_stop_failure_preserves_draft_and_exact_selection(self):
        terminal=self.launch(mode="codex-panel-stop-error",width=36)
        terminal.resize(36,14)
        terminal.contains("Answer: second")
        terminal.paste("keep phone draft")
        self.open_codex_panel(terminal)
        for label in ["Beta worker","Grandchild","101"]:
            terminal.send(b"\x1b[B")
            terminal.contains(label)
        terminal.contains("Process: 101")
        terminal.send(b"x")
        terminal.contains("Selected fixture")
        terminal.contains("stop denied")
        self.assertEqual(terminal.requests("thread/backgroundTerminals/terminate")[0]["params"],
            {"threadId":"thread-original","processId":"101"})
        terminal.resize(18,10)
        terminal.contains("Codex agents")
        terminal.paste("must not edit main draft")
        terminal.wait(lambda:any('must not edit main draft' in line for line in (terminal.root/"keys.log").read_text().splitlines()),"panel consumed paste")
        terminal.send(b"\x1bOQ")
        terminal.resize(100,28)
        terminal.wait(lambda:terminal.input_is("keep phone draft"),"main draft after phone process panel")
        self.assertEqual(terminal.requests("thread/backgroundTerminals/clean"),[])
        self.assertEqual(terminal.requests("turn/interrupt"),[])
        terminal.snapshot("phone-selected-process-failure")

    def test_codex_f2_child_question_survives_parent_result_without_child_text_leak(self):
        terminal=self.launch(mode="codex-panel",width=110)
        terminal.contains("Answer: second")
        terminal.paste("main composer kept")
        self.open_codex_panel(terminal)
        (terminal.root/"panel-step").write_text("child-question")
        terminal.wait(lambda:any(message.get("id")=="child-question-id" for message in terminal.messages("server")),"child native callback")
        terminal.send(b"\x1bOS")
        terminal.contains("Child decision")
        terminal.send(b" \x13")
        terminal.wait(lambda:any(message.get("id")=="child-question-id" and "method" not in message for message in terminal.messages()),"exact child answer")
        response=next(message for message in terminal.messages() if message.get("id")=="child-question-id" and "method" not in message)
        self.assertEqual(response["result"],{"answers":{"child-choice":{"answers":["Yes"]}}})
        terminal.wait(lambda:terminal.input_is("main composer kept"),"callback keeps main composer")
        self.assertNotIn("LATE_CHILD_HIDDEN",terminal.text)
        self.assertEqual(terminal.requests("turn/start"),[])
        self.assertEqual(terminal.requests("turn/steer"),[])
        terminal.snapshot("child-callback-after-parent-completion")

    def test_codex_f2_does_not_retarget_a_vanished_selected_agent_before_explicit_arrow(self):
        terminal=self.launch(mode="codex-panel",width=100)
        terminal.contains("Answer: second")
        self.open_codex_panel(terminal)
        (terminal.root/"panel-step").write_text("remove-alpha")
        terminal.wait(lambda:(terminal.root/"panel-applied").exists() and (terminal.root/"panel-applied").read_text()=="remove-alpha","native membership removed")
        terminal.send(b"r")
        terminal.contains("Selected row unavailable")
        terminal.send(b"x")
        terminal.contains("use arrows")
        self.assertEqual(terminal.requests("turn/interrupt"),[])
        terminal.send(b"\x1b[B")
        terminal.contains("Beta worker")
        terminal.send(b"x")
        terminal.wait(lambda:bool(terminal.requests("turn/interrupt")),"explicit Beta stop")
        self.assertEqual(terminal.requests("turn/interrupt")[0]["params"],{"threadId":"child-b","turnId":"child-turn"})
        terminal.snapshot("vanished-selection-never-retargets-stop")
