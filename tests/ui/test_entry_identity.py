"""Keep the transcript and exact native targets unchanged across a complete reload."""

from pathlib import Path


class EntryIdentity:
    def test_reload_then_rewind_preserves_screen_and_native_target(self):
        root = self.summary_root()
        (root / "bin").mkdir(exist_ok=True)
        (root / "bin/codex").symlink_to(Path(__file__).with_name("entry_identity_fixture.py").resolve())
        (root / "process.py").write_text("print('identity fixture')\n")
        terminal = self.launch_summary(root, mode="summary-identity", resume="thread-original")
        terminal.resize(120, 48)
        terminal.contains("Answer: second")
        terminal.paste("inspect ids")
        terminal.send(b"\r")
        terminal.contains("Approve command execution")
        terminal.send(b"y")
        terminal.wait(lambda: any(row.get("id") == 700 and row.get("result") == {"decision": "accept"}
                                 for row in terminal.messages()), "exact approval reply")
        terminal.contains("Answer: inspect ids")
        terminal.wait(lambda: (root / "summary-requests.jsonl").exists(), "label worker waiting")
        (root / "release-summary").touch()
        terminal.contains("Rewrite the result report")
        terminal.contains("script was not executed")
        terminal.snapshot("streamed-tool-and-delayed-label")
        terminal.paste("DISCONNECT")
        terminal.send(b"\r")
        terminal.contains("Codex stopped")
        terminal.send(b"\x1b[15~")
        terminal.contains("Codex reconnected")
        terminal.contains("Rewrite the result report")
        terminal.contains("script was not executed")
        self.assertEqual(terminal.text.count("Answer: inspect ids"), 1)
        self.assertEqual(terminal.requests("thread/resume")[-1]["params"]["threadId"], "thread-original")
        self.assertGreaterEqual(len(terminal.requests("thread/turns/list")), 2)
        terminal.replace_input("")
        terminal.rewind("inspect ids")
        terminal.replace_input("edited ids")
        terminal.send(b"\r")
        terminal.contains("Answer: edited ids")
        self.assertNotIn("Answer: inspect ids", terminal.text)
        terminal.contains("Answer: first")
        terminal.contains("Answer: second")
        self.assertEqual(terminal.requests("thread/fork")[0]["params"], {
            "threadId": "thread-original", "beforeTurnId": "turn-3", "excludeTurns": True})
        starts = terminal.requests("turn/start")
        self.assertEqual([row["params"]["input"][0]["text"] for row in starts],
                         ["inspect ids", "DISCONNECT", "edited ids"])
        self.assertEqual(starts[-1]["params"]["threadId"], "thread-fork-1")
        self.assertEqual(terminal.requests("thread/rollback"), [])
        self.assertEqual(terminal.requests("turn/steer"), [])
        terminal.snapshot("reload-then-exact-native-rewind")

    def test_invisible_native_users_keep_the_next_visible_prompt_a_steer(self):
        root = self.summary_root()
        (root / "bin").mkdir(exist_ok=True)
        (root / "bin/codex").symlink_to(Path(__file__).with_name("entry_identity_fixture.py").resolve())
        terminal = self.launch(mode="entry-hidden-users", directory=root)
        terminal.contains("Answer: second")
        terminal.contains("you (steer)")
        terminal.rewind("second")
        terminal.send(b"\x1b[A")
        terminal.wait(lambda: terminal.input_is("first"), "select visible steer after hidden users")
        terminal.replace_input("keep this edited steer")
        terminal.send(b"\r")
        terminal.contains("This message is a steer")
        self.assertTrue(terminal.input_is("keep this edited steer"))
        self.assertEqual(terminal.requests("thread/fork"), [])
        self.assertEqual(terminal.requests("turn/start"), [])
        self.assertEqual(terminal.requests("thread/items/list")[-1]["params"]["turnId"], "turn-first")
        terminal.snapshot("invisible-native-users-retain-steer")

    def test_native_override_keeps_a_generated_label_visible_in_full_gutter(self):
        root = self.summary_root()
        (root / "bin").mkdir(exist_ok=True)
        (root / "bin/codex").symlink_to(Path(__file__).with_name("entry_identity_fixture.py").resolve())
        (root / "process.py").write_text("print('label fixture')\n")
        (root / "release-summary").touch()
        terminal = self.launch_summary(root, mode="summary-native-override", resume="thread-original")
        terminal.resize(120, 48)
        terminal.contains("Answer: second")
        terminal.paste("inspect native label")
        terminal.send(b"\r")
        terminal.contains("Rewrite the result report")
        self.tools_command(terminal, "/tools full", "full")
        terminal.paste("native override")
        terminal.send(b"\r")
        terminal.contains("native override probe completed")
        terminal.contains("→ native-label.rs")
        terminal.contains("script was not executed")
        starts = terminal.requests("turn/start")
        self.assertEqual([row["params"]["input"][0]["text"] for row in starts],
                         ["inspect native label", "native override"])
        self.assertTrue(all(row["params"]["threadId"] == "thread-original" for row in starts))
        self.assertEqual(terminal.requests("thread/fork"), [])
        terminal.snapshot("native-override-retains-full-label")
