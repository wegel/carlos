    def test_codex_external_queue_edit_keeps_phone_draft_and_requires_fresh_selection(self):
        terminal=self.launch(mode="codex-controls",width=72)
        terminal.contains("Answer: second")
        terminal.paste("main untouched")
        self.queue_panel(terminal)
        terminal.send(b"e")
        terminal.replace_input("my independent draft")
        (terminal.root/"controls-step").write_text("external-edit")
        terminal.contains("Changed by another client")
        terminal.send(b"\x13")
        terminal.contains("this draft is preserved")
        self.assertEqual(terminal.requests("thread/queue/update"),[])
        terminal.resize(18,10)
        terminal.contains("Resize to edit")
        terminal.paste("MUST_NOT_EDIT")
        terminal.resize(72,20)
        terminal.contains("my independent draft")
        self.assertNotIn("MUST_NOT_EDIT",terminal.text)
        terminal.send(b"\x1b")
        terminal.wait(lambda:"Ctrl+S save" not in terminal.text,"queue editor closed")
        terminal.send(b"\x1b")
        terminal.wait(lambda:terminal.input_is("main untouched"),"phone main draft preserved")
