"""Exercise queue controls and live settings through actual terminal keys and native-shaped replies."""

import json
import shutil


class CodexControls:
    def test_codex_rejected_settings_keep_defaults_and_never_leak_into_normal_prompts(self):
        root=self.summary_root()
        defaults=root/"config/carlos/runtime-defaults.json"
        defaults.parent.mkdir(parents=True)
        defaults.write_text(json.dumps({"model":"fixture-a","effort":"low","summary":"concise"}))
        original=defaults.read_bytes()
        terminal=self.launch(mode="codex-controls-settings-rejected",width=120,directory=root)
        terminal.contains("Answer: second")
        terminal.paste("keep main text")
        terminal.send(b"\x1b[109;5u")
        terminal.contains("Settings")
        terminal.send(b"\x1b[C\r")
        terminal.contains("Managed fixture policy rejected this model")
        terminal.wait(lambda:terminal.input_is("keep main text"),"rejected settings preserve composer")
        self.assertEqual(defaults.read_bytes(),original)
        terminal.send(b"\x1b[109;5u")
        terminal.contains("fixture-b")
        terminal.send(b"\x1b")
        terminal.wait(lambda:"Settings" not in terminal.text,"rejected editor closed")
        terminal.replace_input("after rejected settings")
        terminal.send(b"\r")
        terminal.contains("Answer: after rejected settings")
        for key in ["model","effort","summary"]:
            self.assertNotIn(key,terminal.requests("turn/start")[0]["params"])
        self.assertEqual(defaults.read_bytes(),original)
        self.assertEqual(terminal.requests("config/value/write"),[])

