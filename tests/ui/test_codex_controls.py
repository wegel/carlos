    def test_codex_native_queued_humans_precede_ralph_and_keep_its_complete_gate(self):
        root=self.summary_root()
        prompt=root/".agents/ralph-prompt.md"
        prompt.parent.mkdir()
        prompt.write_text("RALPH_AUTOMATIC_FIXTURE")
        terminal=self.launch(mode="codex-controls-ralph",width=120,directory=root)
        terminal.contains("Answer: second")
        terminal.send(b"\x12")
        terminal.contains("RALPH MODE")
        terminal.paste("main draft while queued humans run")
        self.queue_panel(terminal)
        terminal.contains("queued Alpha")
        self.assertEqual(terminal.requests("turn/start"),[])
        terminal.send(b"s")
        terminal.contains("Selected entry left the queue")
        self.assertEqual(terminal.requests("turn/start"),[])
        terminal.send(b"\x1b[B")
        terminal.contains("queued Beta")
        terminal.send(b"s")
        terminal.wait(lambda:bool(terminal.requests("turn/start")),"automatic work after native humans")
        terminal.send(b"\x1b")
        terminal.contains("Ralph complete")
        self.assertEqual(len(terminal.requests("turn/start")),1)
        self.assertEqual(len(terminal.requests("thread/queue/start")),2)
        methods=[message.get("method") for message in terminal.messages()]
        self.assertLess(max(index for index,method in enumerate(methods) if method=="thread/queue/start"),methods.index("turn/start"))
        self.assertEqual(terminal.requests("turn/steer"),[])
        terminal.wait(lambda:terminal.input_is("main draft while queued humans run"),"automatic work preserves main draft")

    def queue_panel(self,terminal):
        terminal.send(b"\x1bq")
        terminal.contains("Codex queue")
        terminal.wait(lambda:"Refreshing" not in terminal.text,"queue snapshot ready")

    def test_codex_native_queue_edit_reorder_delete_interrupt_and_manual_start(self):
        terminal=self.launch(mode="codex-controls-busy",width=100)
        terminal.contains("Answer: second")
        terminal.wait(lambda:any(message.get("method")=="turn/started" for message in terminal.messages("server")),"native busy turn")
        terminal.send(b"\x1bOR")  # F3 selects native Queue.
        terminal.paste("queued 日本語")
        terminal.send(b"\r")
        terminal.wait(lambda:bool(terminal.requests("thread/queue/add")),"native enqueue")
        terminal.wait(lambda:terminal.input_is(""),"accepted input leaves composer")
        self.assertNotIn("queued 日本語",terminal.text)
        self.assertEqual(terminal.requests("turn/start"),[])
        self.assertEqual(terminal.requests("turn/steer"),[])
        add=terminal.requests("thread/queue/add")[0]["params"]
        self.assertTrue(add["clientUserMessageId"])
        self.assertEqual(add["input"][0]["text"],"queued 日本語")
        self.queue_panel(terminal)
        terminal.contains("queued Alpha")
        terminal.send(b"e")
        terminal.replace_input("edited Alpha")
        terminal.send(b"\x13")
        terminal.contains("acknowledged the queue change")
        terminal.wait(lambda:"Refreshing" not in terminal.text,"edited snapshot ready")
        self.assertEqual(terminal.requests("thread/queue/update")[0]["params"]["queuedSubmissionId"],"queue-a")
        terminal.send(b"\x1b[1;3B")  # Alt+Down reorders selected Alpha after Beta.
        terminal.wait(lambda:bool(terminal.requests("thread/queue/reorder")),"reordered queue")
        terminal.contains("Selected 2/3: queue-a")
        terminal.send(b"\x1b[B")
        terminal.contains("queued 日本語")
        terminal.send(b"d")
        terminal.wait(lambda:bool(terminal.requests("thread/queue/delete")),"deleted selected queue item")
        terminal.wait(lambda:"Refreshing" not in terminal.text,"delete snapshot ready")
        terminal.send(b"\x1b")
        terminal.wait(lambda:"Codex queue" not in terminal.text,"queue panel closed before interrupt")
        terminal.send(b"\x1b")
        terminal.contains("Turn interrupted")
        self.queue_panel(terminal)
        terminal.send(b"\x1b[B")  # Explicitly select after the previous selected ID disappeared.
        terminal.contains("queued Beta")
        terminal.send(b"s")
        terminal.wait(lambda:bool(terminal.requests("thread/queue/start")),"native queued start")
        terminal.send(b"\x1b")
        terminal.contains("Consumed: queued Beta")
        self.assertEqual(terminal.requests("thread/queue/start")[0]["params"]["queuedSubmissionId"],"queue-b")
        self.assertEqual(terminal.text.count("Consumed: queued Beta"),1)
        self.assertEqual(terminal.requests("turn/start"),[])
        self.assertEqual(terminal.requests("turn/steer"),[])
        self.assertEqual(terminal.requests("thread/queue/reorder")[0]["params"]["queuedSubmissionIds"][:2],["queue-b","queue-a"])
        terminal.snapshot("native-queue-consumed-only-once")

    def test_codex_queue_persists_on_resume_and_preserves_the_main_draft(self):
        terminal=self.launch(mode="codex-controls",width=72)
        terminal.contains("Answer: second")
        terminal.paste("keep main draft")
        self.queue_panel(terminal)
        terminal.contains("queued Alpha")
        terminal.send(b"e")
        terminal.replace_input("persisted queued 日本語")
        terminal.send(b"\x13")
        terminal.contains("acknowledged the queue change")
        terminal.send(b"\x1b")
        terminal.wait(lambda:terminal.input_is("keep main draft"),"main editor preserved")
        self.assertNotIn("persisted queued 日本語",terminal.text)
        terminal.close()
        root=terminal.root/"resumed"
        root.mkdir()
        for name in ["server-state.json","queue-state.json"]:
            shutil.copyfile(terminal.root/name,root/name)
        resumed=self.launch(mode="codex-controls",width=72,directory=root)
        resumed.contains("Answer: second")
        self.assertNotIn("persisted queued 日本語",resumed.text)
        self.queue_panel(resumed)
        resumed.contains("persisted queued 日本語")
        self.assertEqual(resumed.requests("turn/start"),[])
        self.assertTrue(all(request["params"]["limit"]==1 for request in resumed.requests("thread/queue/list")))

