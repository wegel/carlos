"""Verify delayed labels, unchanged input/output, history reuse, and local settings."""
import json
import sys
from pathlib import Path


class Summaries:
    def launch_summary(self, directory, mode='summary-live', resume=None):
        settings = directory / 'config/carlos/tool-summaries.json'
        settings.parent.mkdir(parents=True, exist_ok=True)
        settings.write_text(json.dumps({'provider': 'command', 'executable': sys.executable,
            'arguments': [str(Path(__file__).with_name('fake_summary.py').resolve()), str(directory)], 'timeout_seconds': 20}))
        return self.launch(mode=mode, resume=resume, directory=directory, width=100)

    def test_summary_updates_after_answer_without_blocking_input_and_survives_resume(self):
        root = self.summary_root()
        terminal = self.launch_summary(root)
        terminal.resize(100, 48)
        terminal.wait(lambda: terminal.input_is(''), 'ready')
        terminal.paste('inspect commands')
        terminal.send(b'\r')
        terminal.contains('Answer: inspect commands')
        terminal.paste('still typing')
        terminal.wait(lambda: terminal.input_is('still typing'), 'input remains responsive')
        terminal.contains('original output marker')
        self.assertNotIn('Rewrite the result report', terminal.text)
        terminal.wait(lambda: (root / 'summary-requests.jsonl').exists(), 'worker started')
        (root / 'release-summary').touch()
        terminal.contains('Rewrite the result report')
        terminal.contains('Stage and commit source files')
        self.assertTrue(terminal.input_is('still typing'))
        terminal.contains('original output marker')
        terminal.contains('path.write_text(text)')
        terminal.snapshot('async-summary-full')
        terminal.resize(54, 32)
        terminal.contains('Rewrite the result report')
        terminal.contains('Stage and commit source files')
        self.assertNotIn('original output marker', terminal.text)
        terminal.snapshot('async-summary-phone')
        rows = (root / 'summary-requests.jsonl').read_text().splitlines()
        self.assertEqual(len(rows), 2)  # The simple cp is never sent.
        self.assertTrue(all('cp source.txt' not in json.loads(row)['command'] for row in rows))
        terminal.close()
        resumed = self.launch_summary(root, resume='thread-new')
        resumed.resize(54, 32)
        resumed.contains('Rewrite the result report')
        resumed.contains('Stage and commit source files')
        self.assertEqual(len((root / 'summary-requests.jsonl').read_text().splitlines()), 2)
        self.assertEqual(len(resumed.requests('turn/start')), 1)
        self.assertEqual(resumed.requests('turn/steer'), [])
        resumed.snapshot('saved-summary-resumed')

    def test_uncached_history_does_not_start_summarizer_and_setting_stays_local(self):
        root = self.summary_root()
        terminal = self.launch_summary(root, mode='summary-history', resume='thread-original')
        terminal.contains('original output marker')
        terminal.send(b'\x1b[109;5u')
        terminal.contains('AI labels')
        terminal.send(b'\x1b[Z\x1b[Z\x1b[Z')  # Tool output, Layout, AI labels.
        terminal.send(b'\x1b[D')
        terminal.contains('Off')
        terminal.send(b'\r')
        terminal.wait(lambda: 'Settings' not in terminal.text, 'setting applied')
        self.assertFalse(json.loads((root / 'config/carlos/ui-settings.json').read_text())['ai_tool_labels'])
        self.assertFalse((root / 'summary-requests.jsonl').exists())
        self.assertEqual(terminal.requests('turn/start'), [])
        self.assertEqual(terminal.requests('turn/steer'), [])
        terminal.snapshot('summary-settings')

    def test_ep130_short_substantial_heredocs_and_remote_inline_scripts_receive_labels(self):
        root = self.summary_root()
        (root / 'release-summary').touch()
        terminal = self.launch_summary(root, mode='summary-ep130')
        terminal.resize(100, 48)
        terminal.wait(lambda: terminal.input_is(''), 'ready')
        terminal.paste('inspect EP130 commands')
        terminal.send(b'\r')
        terminal.contains('Read saved playback positions')
        terminal.contains('Read remote simulator language preferences')
        terminal.contains('Print the number one')
        terminal.contains('EP130 output marker')
        terminal.contains("p=next(Path(")
        terminal.snapshot('ep130-summary-full')
        terminal.resize(54, 32)
        terminal.contains('Read saved playback positions')
        terminal.contains('Read remote simulator language')
        terminal.contains('Print the number one')
        terminal.snapshot('ep130-summary-phone')
        rows = [json.loads(row) for row in (root / 'summary-requests.jsonl').read_text().splitlines()]
        self.assertEqual(len(rows), 3)
        self.assertTrue(any('rtk proxy ssh' in row['command'] for row in rows))
        self.assertTrue(any('print(1)' in row['command'] for row in rows))
        self.assertTrue(all('process.py' not in row['command'] for row in rows))
        self.assertEqual(len(terminal.requests('turn/start')), 1)
        self.assertEqual(terminal.requests('turn/steer'), [])

    def test_complete_ai_labels_wrap_in_compact_desktop_phone_and_resume(self):
        root = self.summary_root()
        label = 'Read playback records, compare selected language preferences, and write the combined results into the session archive'
        (root / 'summary-label.txt').write_text(label)
        terminal = self.launch_summary(root)
        terminal.wait(lambda: terminal.input_is(''), 'ready')
        terminal.paste('inspect commands')
        terminal.send(b'\r')
        terminal.contains('Answer: inspect commands')
        self.tools_command(terminal, '/tools compact', 'compact')
        (root / 'release-summary').touch()
        terminal.contains('session archive')
        for width in [100, 54, 40, 100]:
            terminal.resize(width, 32)
            terminal.contains('archive')
            terminal.wait(lambda: terminal.text.count('Read playback records') == 2, 'both complete labels')
            text = ' '.join(terminal.text.split())
            self.assertEqual(text.count('session archive'), 2)
            self.assertNotIn('…', terminal.text)
            self.assertNotIn('original output marker', terminal.text)
            terminal.snapshot(f'complete-ai-label-{width}')
        terminal.close()
        resumed = self.launch_summary(root, resume='thread-new')
        resumed.resize(54, 32)
        resumed.wait(lambda: resumed.text.count('archive') == 2, 'saved complete labels')
        self.assertEqual(len((root / 'summary-requests.jsonl').read_text().splitlines()), 2)
        self.assertEqual(len(resumed.requests('turn/start')), 1)
        self.assertEqual(resumed.requests('turn/steer'), [])
