"""Explicit native goal actions preserve drafts, budgets and Ralph ownership."""

class CodexGoals:
    def goal_panel(self,terminal):
        terminal.send(b"\x1bg")
        terminal.contains("Codex goal")
        terminal.wait(lambda:"Goal state: Known" in terminal.text,"current native goal snapshot")

    def goal_applied(self,terminal,count):
        terminal.wait(lambda:len(terminal.requests("thread/goal/set"))==count,"explicit native goal request")
        terminal.wait(lambda:"Goal change pending" not in terminal.text,"goal reply settled")

    def test_codex_goal_create_is_explicit_paused_and_never_replaces_ordinary_chat(self):
        terminal=self.launch(mode="codex-goal-empty",width=120)
        terminal.contains("Answer: second")
        terminal.paste("keep main draft 日本語")
        self.goal_panel(terminal)
        self.assertEqual(terminal.requests("thread/goal/set"),[])
        self.assertEqual(terminal.requests("thread/goal/clear"),[])
        terminal.send(b"e")
        terminal.contains("Field 1/3: Objective")
        terminal.paste("Build an explicit feature 日本語")
        terminal.send(b"\x13")
        self.goal_applied(terminal,1)
        request=terminal.requests("thread/goal/set")[0]["params"]
        self.assertEqual(request,{"threadId":"thread-original","objective":"Build an explicit feature 日本語","status":"paused","origin":"user"})
        terminal.contains("Status: paused")
        terminal.send(b"\x1b")
        terminal.wait(lambda:terminal.input_is("keep main draft 日本語"),"goal editor preserves main draft")
        terminal.replace_input("ordinary chat stays ordinary")
        terminal.send(b"\r")
        terminal.contains("Answer: ordinary chat stays ordinary")
        self.assertEqual(len(terminal.requests("thread/goal/set")),1)
        self.assertEqual(len(terminal.requests("turn/start")),1)
        self.assertEqual(terminal.requests("turn/steer"),[])
        terminal.snapshot("explicit-paused-goal-no-synthetic-chat")

    def test_codex_goal_budget_edits_keep_counters_and_pause_resume_clear_are_user_origin(self):
        terminal=self.launch(mode="codex-goal",width=120)
        terminal.contains("Answer: second")
        self.goal_panel(terminal)
        terminal.contains("Tokens used: 17")
        terminal.send(b"e")
        terminal.paste(" revised")
        terminal.send(b"\t")
        terminal.paste("4096")
        terminal.send(b"\x13")
        self.goal_applied(terminal,1)
        first=terminal.requests("thread/goal/set")[0]["params"]
        self.assertEqual(first["tokenBudget"],4096)
        self.assertEqual(first["status"],"paused")
        terminal.contains("Tokens used: 17")
        terminal.contains("Time used (seconds): 3")
        terminal.send(b"e")
        terminal.paste(" final")
        terminal.send(b"\x13")
        self.goal_applied(terminal,2)
        self.assertNotIn("tokenBudget",terminal.requests("thread/goal/set")[1]["params"])
        terminal.contains("Token budget: 4096")
        terminal.send(b"a")
        terminal.contains("may start model work immediately")
        self.assertEqual(len(terminal.requests("thread/goal/set")),2)
        terminal.send(b"y")
        self.goal_applied(terminal,3)
        terminal.contains("Status: active")
        terminal.send(b"p")
        self.goal_applied(terminal,4)
        terminal.contains("Status: paused")
        terminal.send(b"d")
        terminal.contains("Clear the saved goal")
        terminal.send(b"n")
        self.assertEqual(terminal.requests("thread/goal/clear"),[])
        terminal.send(b"dy")
        terminal.wait(lambda:bool(terminal.requests("thread/goal/clear")),"explicit native clear")
        terminal.contains("No saved goal reported")
        for request in terminal.requests("thread/goal/set")+terminal.requests("thread/goal/clear"):
            self.assertEqual(request["params"]["origin"],"user")
        self.assertEqual(terminal.requests("turn/start"),[])
        terminal.snapshot("goal-budget-keep-counters-and-user-actions")

    def test_codex_goal_pending_activation_cannot_enable_ralph_and_plain_chat_remains_usable(self):
        root=self.summary_root()
        prompt=root/".agents/ralph-prompt.md"
        prompt.parent.mkdir()
        prompt.write_text("RALPH_MUST_NOT_RUN")
        terminal=self.launch(mode="codex-goal-delayed",width=120,directory=root)
        terminal.contains("Answer: second")
        self.goal_panel(terminal)
        terminal.send(b"ay")
        terminal.contains("Goal change pending")
        terminal.send(b"\x12")
        terminal.contains("pending Codex goal change")
        terminal.send(b"\x1b")
        terminal.wait(lambda:"Codex goal · Esc back" not in terminal.text,"goal panel closes")
        terminal.paste("human while activation pending")
        terminal.send(b"\r")
        terminal.contains("Answer: human while activation pending")
        (root/"goal-step").write_text("release-activate")
        terminal.wait(lambda:(root/"goal-applied").exists(),"native activation reply released")
        self.assertEqual(len(terminal.requests("turn/start")),1)
        self.assertNotIn("RALPH_MUST_NOT_RUN",str(terminal.requests("turn/start")))
        self.assertEqual(terminal.requests("turn/steer"),[])
        terminal.snapshot("pending-goal-activation-never-starts-ralph")

    def test_codex_goal_phone_resize_and_rejected_save_preserve_goal_and_main_drafts(self):
        terminal=self.launch(mode="codex-goal-reject",width=36)
        terminal.resize(36,14)
        terminal.contains("Answer: second")
        terminal.paste("phone main draft")
        self.goal_panel(terminal)
        terminal.send(b"e")
        terminal.paste(" 修正")
        terminal.resize(18,10)
        terminal.contains("Resize to edit")
        terminal.paste("IGNORED_TINY_GOAL_PASTE")
        terminal.wait(lambda:"IGNORED_TINY_GOAL_PASTE" in (terminal.root/"keys.log").read_text(),"fallback consumed paste")
        terminal.send(b"\x13")
        self.assertEqual(terminal.requests("thread/goal/set"),[])
        terminal.resize(100,30)
        terminal.contains(" 修正")
        terminal.send(b"\x13")
        terminal.contains("Managed goal policy rejected")
        self.assertTrue(terminal.requests("thread/goal/set")[0]["params"]["objective"].endswith(" 修正"))
        terminal.send(b"\x1b")
        terminal.contains("Codex goal")
        terminal.send(b"p")
        terminal.wait(lambda:len(terminal.requests("thread/goal/set"))==2,"pause without saving unsent edits")
        self.assertNotIn("objective",terminal.requests("thread/goal/set")[1]["params"])
        terminal.send(b"e")
        terminal.contains(" 修正")
        terminal.send(b"\x1b")
        terminal.wait(lambda:"Field 1/3" not in terminal.text,"goal editor returned to overview")
        terminal.send(b"\x1b")
        terminal.wait(lambda:terminal.input_is("phone main draft"),"goal failure keeps main composer")
        self.assertEqual(terminal.requests("turn/start"),[])
        terminal.snapshot("phone-goal-failure-keeps-both-drafts")

    def test_codex_goal_command_inside_rewind_remains_literal_user_text(self):
        terminal=self.launch(mode="codex-goal",width=120)
        terminal.contains("Answer: second")
        terminal.rewind("second")
        terminal.replace_input("/goal")
        terminal.send(b"\r")
        terminal.contains("Answer: /goal")
        self.assertEqual(len(terminal.requests("thread/fork")),1)
        self.assertEqual(terminal.requests("thread/goal/set"),[])
        self.assertEqual(terminal.requests("thread/goal/clear"),[])
        self.assertEqual(terminal.requests("turn/start")[-1]["params"]["input"][0]["text"],"/goal")
        terminal.snapshot("literal-goal-rewind-prompt")

    def test_codex_goal_disabled_feature_is_visible_and_never_creates_a_hidden_chat_substitute(self):
        terminal=self.launch(mode="codex-goal-disabled",width=100)
        terminal.contains("Answer: second")
        terminal.send(b"\x1bg")
        terminal.contains("Unavailable/disabled")
        terminal.contains("goals feature is disabled")
        terminal.send(b"e")
        terminal.contains("Read the current Codex goal before editing")
        self.assertEqual(terminal.requests("thread/goal/set"),[])
        terminal.send(b"\x1b")
        terminal.wait(lambda:"Codex goal · Esc back" not in terminal.text,"disabled goal panel closes")
        terminal.paste("ordinary chat despite disabled goals")
        terminal.send(b"\r")
        terminal.contains("Answer: ordinary chat despite disabled goals")
        self.assertEqual(len(terminal.requests("turn/start")),1)
        self.assertEqual(terminal.requests("thread/goal/clear"),[])
