    def test_codex_active_and_queued_resolutions_preserve_phone_drafts_without_replay(self):
        terminal=self.launch(mode="codex-questions",width=36)
        terminal.contains("Answer: second")
        self.callback_step(terminal,"questions")
        terminal.contains("Choose a route")
        terminal.send(b"\x1bOS")
        terminal.contains("Secret answer")
        terminal.paste("preserved-secret")
        self.callback_step(terminal,"resolve-numeric")
        terminal.wait(lambda:any(message.get("method")=="serverRequest/resolved" and message["params"]["requestId"]==9 for message in terminal.messages("server")),"queued numeric resolution")
        terminal.resize(18,10)
        terminal.contains("Resize to edit")
        before=(terminal.root/"keys.log").read_text().count("secret input (redacted)")
        terminal.paste("must-not-replace-draft")
        terminal.wait(lambda:(terminal.root/"keys.log").read_text().count("secret input (redacted)")>before,"paste handled before enlarging")
        terminal.resize(36,14)
        terminal.contains("Secret answer")
        terminal.send(b"\x13")
        terminal.wait(lambda:bool(self.codex_answers(terminal,"9")),"secret draft after resize")
        self.assertEqual(self.codex_answers(terminal,"9")[0]["result"],{"answers":{"native-answer-key":{"answers":["user_note: preserved-secret"]}}})
        self.assertEqual(self.codex_answers(terminal,9),[])
        self.callback_step(terminal,"replay")
        terminal.wait(lambda:sum(message.get("method")=="item/tool/requestUserInput" for message in terminal.messages("server"))==4,"replayed callbacks delivered")
        terminal.wait(lambda:terminal.input_is(""),"resolved callbacks stay gone")
        self.no_answer_prompts(terminal)
