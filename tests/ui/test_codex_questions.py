    def test_codex_concurrent_approval_kinds_keep_their_own_wire_responses(self):
        terminal=self.launch(mode="codex-questions",width=72)
        terminal.contains("Answer: second")
        self.callback_step(terminal,"approvals")
        terminal.contains("echo command-checkpoint")
        terminal.wait(lambda:sum("id" in message and message.get("method") in ["item/commandExecution/requestApproval","item/permissions/requestApproval","applyPatchApproval","item/fileChange/requestApproval"] for message in terminal.messages("server"))==4,"all approval kinds queued")
        terminal.send(b"y")
        terminal.contains("Allow this network request")
        terminal.send(b"s")
        terminal.contains("visible patch content")
        terminal.send(b"n")
        terminal.contains("Update the generated file")
        terminal.send(b"c")
        terminal.wait(lambda:bool(self.codex_answers(terminal,"file")),"all approval replies")
        expected={"command":{"decision":"accept"},"permissions":{"permissions":{"network":{"enabled":True}},"scope":"session"},"legacy-patch":{"decision":"denied"},"file":{"decision":"cancel"}}
        for request_id,result in expected.items():
            self.assertEqual(self.codex_answers(terminal,request_id)[0]["result"],result)
        self.no_answer_prompts(terminal)

    def callback_step(self, terminal, step):
        (terminal.root/"callback-step").write_text(step)

    def codex_answers(self, terminal, request_id=None):
        replies=[message for message in terminal.messages() if "method" not in message and "result" in message]
        if request_id is None:
            return replies
        return [reply for reply in replies if type(reply["id"]) is type(request_id) and reply["id"]==request_id]

    def no_answer_prompts(self, terminal):
        self.assertEqual(terminal.requests("turn/start"),[])
        self.assertEqual(terminal.requests("turn/steer"),[])

    def test_codex_concurrent_child_questions_keep_native_ids_and_secret_drafts(self):
        terminal=self.launch(mode="codex-questions",width=100)
        terminal.contains("Answer: second")
        terminal.paste("main composer stays")
        self.callback_step(terminal,"questions")
        terminal.contains("Choose a route")
        terminal.contains("The red route")
        self.assertNotIn("Esc back",terminal.text,"blocking questions cannot return to composer")
        terminal.send(b" \t")  # Explicitly select Red, then the Unicode free-text field.
        terminal.paste("日本語 🦀")
        terminal.send(b"\x1bOS")  # F4 moves to the independent string-ID callback.
        terminal.contains("Secret answer")
        terminal.paste("PRIVATE_SECRET_α")
        terminal.wait(lambda:"•" in terminal.text,"secret mask")
        self.assertNotIn("PRIVATE_SECRET_α",terminal.text)
        terminal.send(b"\t")  # The review page must stay masked too.
        terminal.contains("(hidden)")
        terminal.paste("REVIEW_SECRET_SHOULD_BE_IGNORED")
        self.assertNotIn("PRIVATE_SECRET_α",terminal.text)
        terminal.snapshot("secret-review")
        trace=(terminal.root/"keys.log").read_text()
        self.assertNotIn("PRIVATE_SECRET_α",trace)
        self.assertNotIn("REVIEW_SECRET_SHOULD_BE_IGNORED",trace)
        terminal.send(b"\x1bOS")
        terminal.contains("Unicode text")
        terminal.send(b"\x13")
        terminal.wait(lambda:bool(self.codex_answers(terminal,9)),"numeric native answer")
        self.assertEqual(self.codex_answers(terminal,9)[0]["result"],{"answers":{
            "native-answer-key":{"answers":["Red"]},"unicode-key":{"answers":["user_note: 日本語 🦀"]}}})
        terminal.contains("(hidden)")
        terminal.send(b"\x13")
        terminal.wait(lambda:bool(self.codex_answers(terminal,"9")),"string native answer")
        self.assertEqual(self.codex_answers(terminal,"9")[0]["result"],{"answers":{"native-answer-key":{"answers":["user_note: PRIVATE_SECRET_α"]}}})
        terminal.wait(lambda:terminal.input_is("main composer stays"),"main draft restored")
        for private in ["PRIVATE_CHILD_TEXT","PRIVATE_CHILD_TOOL","PRIVATE_CHILD_OUTPUT"]:
            self.assertNotIn(private,terminal.text)
        self.no_answer_prompts(terminal)

    def test_codex_nonblocking_focus_and_later_human_approval_use_one_time_decisions(self):
        terminal=self.launch(mode="codex-questions",width=72)
        terminal.contains("Answer: second")
        self.callback_step(terminal,"nonblocking")
        terminal.contains("F4: Codex request waiting")
        terminal.paste("main draft")
        terminal.wait(lambda:terminal.input_is("main draft"),"nonblocking composer")
        terminal.send(b"\x1bOS")
        terminal.contains("Choose a route")
        terminal.contains("Esc back")
        terminal.paste("saved question draft")
        terminal.send(b"\x1b")
        terminal.wait(lambda:terminal.input_is("main draft"),"nonblocking question hidden")
        self.callback_step(terminal,"blocking")
        terminal.contains("One-time human approval")
        self.assertNotIn("s accept session",terminal.text)
        terminal.send(b"s")
        self.assertEqual(self.codex_answers(terminal,"human-command"),[])
        terminal.send(b"y")
        terminal.wait(lambda:bool(self.codex_answers(terminal,"human-command")),"one-time answer")
        self.assertEqual(self.codex_answers(terminal,"human-command")[0]["result"],{"decision":"accept"})
        terminal.wait(lambda:terminal.input_is("main draft"),"hidden question stays nonblocking")
        terminal.send(b"\x1bOS")
        terminal.contains("saved question draft")
        terminal.send(b"\x1bn")
        terminal.wait(lambda:bool(self.codex_answers(terminal,"nonblocking")),"explicit skip")
        self.assertEqual(self.codex_answers(terminal,"nonblocking")[0]["result"],{"answers":{}})
        self.no_answer_prompts(terminal)

