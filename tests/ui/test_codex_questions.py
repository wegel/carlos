"""Answer native Codex callbacks without generating human prompts or losing drafts."""

import json


class CodexQuestions:
    def test_codex_successful_fork_retires_hidden_callbacks_and_late_replays(self):
        terminal=self.launch(mode="codex-questions",width=100)
        terminal.contains("Answer: second")
        self.callback_step(terminal,"nonblocking")
        terminal.contains("F4: Codex request waiting")
        terminal.send(b"\x1bOS")
        terminal.contains("Choose a route")
        terminal.paste("old question draft")
        terminal.send(b"\x1b")
        self.callback_step(terminal,"quiet")
        terminal.wait(lambda:any(message.get("method")=="turn/completed" and message["params"]["turn"]["id"]=="root-busy" for message in terminal.messages("server")),"root finished")
        self.edit(terminal,"second","forked question cleanup")
        self.callback_step(terminal,"old-replay")
        terminal.wait(lambda:any(message.get("method")=="serverRequest/resolved" and message["params"].get("requestId")=="nonblocking" for message in terminal.messages("server")),"old resolution delivered")
        terminal.send(b"\x1bOS")
        terminal.paste("new main draft")
        terminal.wait(lambda:terminal.input_is("new main draft"),"old overlay stays retired")
        self.assertNotIn("old question draft",terminal.text)
        self.assertEqual(self.codex_answers(terminal,"nonblocking"),[])
        self.assertEqual(len(terminal.requests("thread/fork")),1)
        self.assertEqual(len(terminal.requests("turn/start")),1)
        self.assertEqual(terminal.requests("turn/steer"),[])

