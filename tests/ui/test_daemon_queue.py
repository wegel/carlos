    def disconnect_queue_terminal(self, terminal):
        import socket
        for peer in list(terminal.daemon_recorder.peers):
            try:
                peer.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
        terminal.contains("F5 reconnects")

