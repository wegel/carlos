"""Drive native queue keys through actual terminals, daemon dispatch, and the native peer."""

import copy


def queue_entry(identity, text, rich=False):
    return {"id": identity, "clientUserMessageId": "external-human", "input": [
        {"type": "text", "text": text, "text_elements": [{"future": "retained"}] if rich else []}]}


class DaemonQueue:
    def daemon_queue(self, name, entries=None, width=120, enabled=True):
        fixture, client, session = self.daemon_session(name)
        fixture.native.queue_enabled = enabled
        fixture.native.queue_entries = entries or []
        terminal = self.attach_daemon(fixture, session, name, width=width)
        terminal.contains("history.txt" if width < 80 else "history-output 9999")
        return fixture, client, session, terminal

    def open_daemon_queue(self, terminal, count=None):
        terminal.send(b"\x1bq")
        terminal.contains("Codex queue")
        self.queue_current(terminal, count)

    def queue_current(self, terminal, count=None):
        expected = "Current:" if count is None else f"Current: {count} queued"
        terminal.wait(lambda: expected in terminal.text and "Refreshing" not in terminal.text,
                      "current bounded native queue page")

    def queue_changed(self, terminal, count, queued):
        terminal.wait(lambda: len(terminal.requests("queue/change")) == count, "typed native queue change")
        self.queue_current(terminal, queued)
        terminal.wait(lambda: "Queue request pending" not in terminal.text, "private queue acknowledgement")

