    def test_daemon_queue_rejection_keeps_a_newer_composer_and_another_terminals_draft(self):
        import asyncio
        fixture, client, session, terminal = self.daemon_queue("queue-private-rejection")
        other = self.attach_daemon(fixture, session, "queue-private-observer")
        other.contains("history-output 9999")
        other.paste("another terminal's draft")
        other.wait(lambda: other.input_is("another terminal's draft"), "independent observer composer")
        self.open_daemon_queue(terminal, 0)
        terminal.send(b"\x1bOR")
        terminal.send(b"\x1b")
        terminal.wait(lambda: "Codex queue" not in terminal.text, "queue mode selected without editing composer")
        held = {}
        original = fixture.native.queue_request
        async def reject_later(link, request):
            if request["method"] == "thread/queue/add":
                held.update(link=link, identity=request["id"])
            else:
                await original(link, request)
        fixture.native.queue_request = reject_later
        terminal.paste("rejected original queue input 🌍")
        terminal.send(b"\r")
        terminal.wait(lambda: bool(held), "native add admitted before its failure")
        terminal.wait(lambda: terminal.input_is(""), "submitted input retained privately")
        terminal.paste("newer main draft")
        terminal.wait(lambda: terminal.input_is("newer main draft"), "newer local draft")
        asyncio.run_coroutine_threadsafe(fixture.native.send(held["link"], {
            "id": held["identity"], "error": {"code": -32602, "message": "PRIVATE_QUEUE_REJECTION"}}), fixture.native.loop).result(timeout=3)
        terminal.contains("PRIVATE_QUEUE_REJECTION")
        terminal.contains("Unsent private draft retained")
        self.assertNotIn("PRIVATE_QUEUE_REJECTION", other.text)
        terminal.send(b"v")
        terminal.contains("Clear or save the main draft")
        terminal.send(b"\x1b")
        terminal.wait(lambda: terminal.input_is("newer main draft"), "queue failure keeps newer composer")
        terminal.replace_input("")
        terminal.wait(lambda: terminal.input_is(""), "empty composer for explicit recovery")
        self.open_daemon_queue(terminal, 0)
        terminal.send(b"v")
        terminal.wait(lambda: terminal.input_is("rejected original queue input 🌍"), "explicit recovery uses only the failed operation")
        self.assertTrue(other.input_is("another terminal's draft"))
        self.assertEqual(len(terminal.requests("queue/change")), 1)
        self.assertEqual(terminal.requests("session/send"), [])
        self.assertEqual(other.requests("queue/change"), [])
        terminal.snapshot("daemon-private-queue-recovery")

