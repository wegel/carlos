        self.assertNotIn("NEVER_SHOW_SECRET", terminal.text)
        self.assertNotIn("HIDDEN_SIGNATURE", terminal.text)
        self.assertEqual(len(self.helper_requests(terminal, "prompt")), 1)
        terminal.snapshot("native-thinking")
        terminal.send(b"\x1b")
        terminal.contains("Turn interrupted")

