    def test_claude_native_reset_keeps_pipelined_human_once_and_uses_observed_session_id(self):
        terminal = self.launch(mode="claude-native-reset",backend="claude",resume=None,width=140)
        self.claude_ready(terminal)
        self.submit_native(terminal,"old conversation")
        self.fence_native(terminal,1)
        self.submit_native(terminal,"/clear")
        terminal.wait(lambda: len(self.helper_requests(terminal,"prompt")) == 2,"clear accepted")
        self.submit_native(terminal,"survives clear 日本語")
        terminal.contains("After reset once: survives clear 日本語")
        self.fence_native(terminal,3)
        self.assertNotIn("Answer: old conversation",terminal.text)
        self.assertEqual(terminal.text.count("After reset once: survives clear 日本語"),1)
        frames = terminal.messages("server")
        reset = next(frame for frame in frames if frame.get("type") == "conversation_reset")
        actual = [frame for frame in frames if frame.get("subtype") == "init"][-1]["session_id"]
        self.assertNotEqual(reset["new_conversation_id"],actual)
        self.assertEqual(len(self.helper_requests(terminal,"prompt")),3)
        terminal.rewind("survives clear 日本語")
        terminal.send(b"\x1b[A")
        terminal.wait(lambda: terminal.input_is("survives clear 日本語"),"only surviving human is editable")
        terminal.send(b"\x1b")
        terminal.snapshot("native-reset-survivor")

